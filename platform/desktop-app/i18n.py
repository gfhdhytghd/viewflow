def resolve_language(preference, system_locale):
    if preference in ('en', 'zh-CN'):
        return preference
    return 'zh-CN' if system_locale.lower().replace('_', '-').startswith('zh') else 'en'


def translate(source, language, **values):
    template = EN.get(source, source) if language == 'en' else source
    return template.format(**values) if values else template


# Existing runtime helpers retain their source-language status strings. Translate
# only known, anchored templates at the presentation boundary, never arbitrary substrings.
_DYNAMIC = [(re.compile('^' + re.sub(r'\\\{\w+\\\}', '(.*)', re.escape(key)) + '$'),
             key, re.findall(r'\{(\w+)\}', key)) for key in EN if '{' in key]


def status_text(source, language):
    if language != 'en' or source in EN:
        return translate(source, language)
    for pattern, key, fields in _DYNAMIC:
        match = pattern.fullmatch(source)
        if match:
            return translate(key, language, **dict(zip(fields, match.groups())))
    return source

