// Generate the C++ broker mapping from the existing service's supported HID keys.
// cargo run -q -p viewflow-platform --example windows-handoff-key-table > platform/desktop-handoff/service_keys.inc
fn generated() -> String {
    use std::fmt::Write;
    let mut result = String::from("// Generated by windows-handoff-key-table; do not edit by hand.\n");
    for page in [7, 12] {
        for usage in 0..=0x2ff {
            if let Some(key) = viewflow_platform::windows_input::hid_usage_to_windows_scan_code(page, usage) {
                writeln!(result, "{{0x{:04x}, {}, {}}},", u32::from(key.code) | if key.extended {0xe000} else {0}, page, usage).unwrap();
            }
        }
    }
    result
}
fn main() { print!("{}", generated()); }
#[test]
fn committed_handoff_table_matches_service_backend() {
    assert_eq!(generated(), include_str!("../../../platform/desktop-handoff/service_keys.inc"));
}
